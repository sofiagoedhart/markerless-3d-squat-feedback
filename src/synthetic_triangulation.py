"""Reconstruction error of the DLT under known image-space noise, on this rig."""
from __future__ import annotations
import argparse
import csv
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dlt_triangulation import triangulate_point_dlt, project
from multiview_triangulate import Camera


def load_rig(indices, path=None):
    """Cameras straight from calib/extrinsics.json."""
    if path is None:
        here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        path = os.path.join(here, "calib", "extrinsics.json")
    data = json.load(open(path))
    cams = data["cameras"]
    rig = []
    for i in indices:
        if str(i) not in cams:
            raise SystemExit(f"cam{i} not in {path} (has {list(cams)})")
        c = cams[str(i)]
        rig.append(Camera(np.array(c["K"]), np.array(c["R"]), np.array(c["t"]),
                          name=f"cam{i}"))
    print(f"Rig from {path} (units: {data.get('units', 'mm')}), "
          f"cameras {list(indices)}")
    return rig

DEFAULT_BOX = np.array([[-700.0, 700.0], [-700.0, 700.0], [0.0, 1900.0]])


def volume_from_recordings(session, margin=50.0):
    """The bounding box of every reconstructed joint in a recorded session."""
    files = sorted(f for f in glob.glob(os.path.join(session, "*.npz"))
                   if "frametimes" not in f)
    if not files:
        raise SystemExit(f"no .npz sets in {session}")
    lo = np.full(3, np.inf)
    hi = np.full(3, -np.inf)
    n = 0
    for f in files:
        kp = np.load(f, allow_pickle=True)["kp"]
        pts = kp.reshape(-1, 3)
        pts = pts[np.all(np.isfinite(pts), axis=1)]
        if pts.size:
            lo = np.minimum(lo, pts.min(axis=0))
            hi = np.maximum(hi, pts.max(axis=0))
            n += len(pts)
    if not np.all(np.isfinite(lo)):
        raise SystemExit("no finite joints in that session")
    print(f"Capture volume from {len(files)} sets, {n} joint samples:")
    for ax, a, b in zip("xyz", lo, hi):
        print(f"   {ax}: {a:8.0f} .. {b:8.0f} mm")
    return np.stack([lo - margin, hi + margin], axis=1)


def in_view(P, X, size):
    """True when the point projects inside the image."""
    Xh = np.append(np.asarray(X, float), 1.0)
    x = P @ Xh
    if x[2] <= 0:
        return False
    u, v = x[0] / x[2], x[1] / x[2]
    return 0 <= u < size[0] and 0 <= v < size[1]


def sweep(rig, box, noises, n_points, size, seed=0):
    """-> rows of (noise_px, views, mean, median, p95, max, n)."""
    rng = np.random.default_rng(seed)
    Ps = [c.P for c in rig]

    pts, tries = [], 0
    while len(pts) < n_points and tries < n_points * 200:
        tries += 1
        X = np.array([rng.uniform(*box[0]), rng.uniform(*box[1]), rng.uniform(*box[2])])
        if all(in_view(P, X, size) for P in Ps):
            pts.append(X)
    if len(pts) < n_points:
        print(f"only {len(pts)} of {n_points} sampled points are visible in all "
              f"{len(Ps)} views - the box may be larger than the shared field of view")
    pts = np.array(pts)

    rows = []
    for nv in (2, 3):
        if nv > len(Ps):
            continue
        use = Ps[:nv]
        for s in noises:
            err = []
            for X in pts:
                obs = []
                for P in use:
                    x = project(P, X)
                    obs.append(x + rng.normal(0.0, s, 2) if s > 0 else x)
                Xh = triangulate_point_dlt(use, obs)
                err.append(float(np.linalg.norm(Xh - X)))
            e = np.array(err)
            rows.append((s, nv, e.mean(), np.median(e), np.percentile(e, 95),
                         e.max(), len(e)))
            print(f"  {nv} views  noise {s:4.1f} px -> mean {e.mean():7.2f}  "
                  f"median {np.median(e):7.2f}  p95 {np.percentile(e,95):7.2f}  "
                  f"max {e.max():8.2f} mm")
    return rows, pts


def write_csv(rows, path):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(("noise_px", "views", "mean_mm", "median_mm", "p95_mm",
                    "max_mm", "points"))
        for r in rows:
            w.writerow([r[0], r[1]] + [round(v, 3) for v in r[2:6]] + [r[6]])
    print(f"\nwrote {path}")


def write_tex(rows, path):
    """The 3-view rows as Chapter 6's table 6.3, ready to \\input."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write("% generated by src/synthetic_triangulation.py\n")
        f.write("\\begin{tabular}{cccc}\n\\hline\n")
        f.write("Image noise (px) & Mean error (mm) & Median error (mm) & "
                "Maximum error (mm) \\\\\n\\hline\n")
        for s, nv, mean, med, p95, mx, n in rows:
            if nv != 3:
                continue
            f.write(f"{s:.1f} & {mean:.2f} & {med:.2f} & {mx:.2f} \\\\\n")
        f.write("\\hline\n\\end{tabular}\n")
    print(f"wrote {path}")


def plot(rows, path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        print("matplotlib not available - skipping the plot")
        return
    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    for nv, style in ((2, "--o"), (3, "-o")):
        r = [x for x in rows if x[1] == nv]
        if not r:
            continue
        s = [x[0] for x in r]
        mean = [x[2] for x in r]
        p95 = [x[4] for x in r]
        ax.plot(s, mean, style, label=f"{nv} views (mean)")
        ax.fill_between(s, mean, p95, alpha=0.15)
    ax.set_xlabel("Image-space noise (px, per view, Gaussian)")
    ax.set_ylabel("Reconstruction error (mm)")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fig.savefig(path, dpi=200)
    print(f"wrote {path}  (shaded band = mean to 95th percentile)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cams", nargs="*", type=int, default=[0, 1, 2])
    ap.add_argument("--points", type=int, default=1000)
    ap.add_argument("--noise", type=float, nargs="+", default=[0.0, 0.5, 1.0, 2.0])
    ap.add_argument("--volume-from", default=None,
                    help="recordings/<session> - sample inside the box the athlete "
                         "actually occupied instead of the default one")
    ap.add_argument("--image-size", type=int, nargs=2, default=[1280, 720],
                    metavar=("W", "H"))
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="results/synthetic_triangulation.csv")
    ap.add_argument("--tex", default="results/synthetic_triangulation.tex")
    ap.add_argument("--plot", default="results/synthetic_triangulation.png")
    a = ap.parse_args()

    rig = load_rig(a.cams)
    box = (volume_from_recordings(a.volume_from) if a.volume_from
           else DEFAULT_BOX)
    print(f"\n{a.points} points, {len(rig)} cameras, image {a.image_size[0]}x"
          f"{a.image_size[1]}, noise {a.noise} px\n")
    rows, pts = sweep(rig, box, a.noise, a.points, a.image_size, a.seed)

    zero = [r for r in rows if r[0] == 0.0 and r[1] == len(rig)]
    if zero and zero[0][3] > 1e-6:
        print(f"\nmedian error at 0 px is {zero[0][3]:.4f} mm, not ~0. The DLT "
              f"should recover a noise-free point exactly; check the calibration "
              f"file rather than reporting this as accuracy.")
    write_csv(rows, a.out)
    write_tex(rows, a.tex)
    if a.plot:
        plot(rows, a.plot)


if __name__ == "__main__":
    main()
